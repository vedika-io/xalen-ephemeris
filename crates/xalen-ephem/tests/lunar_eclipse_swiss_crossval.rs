fn contacts(e: &LunarEclipse) -> [Option<f64>; 6] {
    let c = e.contacts;
    [
        c.penumbral_begin,
        c.partial_begin,
        c.total_begin,
        c.total_end,
        c.partial_end,
        c.penumbral_end,
    ]
}

fn seconds(a: f64, b: f64) -> f64 {
    (a - b).abs() * 86400.0
}

fn assert_matches(row: &Row, e: &LunarEclipse) {
    let (date, kind, maximum, umbral, penumbral, times) = *row;
    assert_eq!(e.eclipse_type, kind, "{date}: type");
    let dt = seconds(e.jd_maximum, maximum);
    assert!(dt < MAXIMUM_TOLERANCE_S, "{date}: maximum off by {dt:.1}s");
    if umbral > 0.0 {
        let du = (e.umbral_magnitude - umbral).abs();
        assert!(
            du < MAGNITUDE_TOLERANCE,
            "{date}: umbral magnitude off by {du}"
        );
    } else {
        assert!(
            e.umbral_magnitude < MAGNITUDE_TOLERANCE,
            "{date}: umbral magnitude {}",
            e.umbral_magnitude
        );
    }
    let dp = (e.penumbral_magnitude - penumbral).abs();
    assert!(
        dp < MAGNITUDE_TOLERANCE,
        "{date}: penumbral magnitude off by {dp}"
    );
    for (i, (ours, swiss)) in contacts(e).into_iter().zip(times).enumerate() {
        match ours {
            Some(t) => {
                let dc = seconds(t, swiss);
                assert!(
                    swiss > 0.0 && dc < CONTACT_TOLERANCE_S,
                    "{date}: contact {i} off by {dc:.1}s"
                );
            }
            None => assert_eq!(swiss, 0.0, "{date}: contact {i} missing"),
        }
    }
}

#[test]
fn every_lunar_eclipse_2020_to_2030_matches_swiss() {
    let found = find_lunar_eclipses(&Almanac::default_vedic(), 2458849.5, 2462867.5);
    let expected: Vec<&Row> = SWISS.iter().filter(|r| r.0 >= "2020").collect();
    let dates: Vec<f64> = found.iter().map(|e| e.jd_maximum).collect();
    assert_eq!(found.len(), expected.len(), "eclipses found at {dates:?}");
    for (row, e) in expected.into_iter().zip(&found) {
        assert_matches(row, e);
    }
}

#[test]
fn historical_lunar_eclipses_match_swiss() {
    let almanac = Almanac::default_vedic();
    for row in SWISS.iter().filter(|r| r.0 < "2020") {
        let found = find_lunar_eclipses(&almanac, row.2 - 1.0, row.2 + 1.0);
        assert_eq!(found.len(), 1, "{}: eclipses found", row.0);
        assert_matches(row, &found[0]);
    }
}

#[test]
fn full_moons_clear_of_the_penumbra_are_not_eclipses() {
    let almanac = Almanac::default_vedic();
    for jd in [2416718.5, 2440284.5, 2446869.5, 2453454.5] {
        let found = find_lunar_eclipses(&almanac, jd - 2.0, jd + 2.0);
        assert!(found.is_empty(), "phantom eclipse near JD {jd}: {found:?}");
    }
}
