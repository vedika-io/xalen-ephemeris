//! Swiss Ephemeris house-cusp oracle for every house system XALEN supports.
//!
//! # What this proves
//! For each `HouseSystem`, the 12 ecliptic-longitude cusps produced by
//! `xalen_houses::compute_houses` are checked against Swiss Ephemeris ground
//! truth across five latitudes (0°, 28°, 51°, 60°, -34°) and two epochs
//! (J2000.0 and JD 2460000.5-ish, 2023-02-24).
//!
//! # How the oracle isolates the house-DIVISION algorithm
//! XALEN and Swiss Ephemeris frame a chart slightly differently: XALEN's house
//! cusps are built from XALEN's own sidereal time (`gmst`/`local_sidereal_time`
//! → `compute_ramc`) and the IAU 2006 **mean** obliquity, whereas a bare
//! `swe_houses_ex(jd, lat, lon, …)` call uses Swiss's internal sidereal time and
//! the **true** obliquity (mean + nutation). Those framing differences offset
//! the Ascendant/MC by a few thousandths of a degree even when the house
//! algorithm is bit-identical — noise that would mask real algorithm bugs.
//!
//! To remove that noise the reference cusps were produced by pyswisseph's
//! `swe.houses_armc(armc, lat, eps, hsys)` fed the **same** RAMC and the **same**
//! IAU 2006 mean obliquity that XALEN uses. With identical (ARMC, ε, φ) inputs,
//! `houses_armc` reproduces XALEN's MC/ASC to 1e-6°, so any residual cusp
//! disagreement is purely the house-division algorithm — exactly what we want
//! to test.
//!
//! # Reference generation (anti-fabrication)
//! Every baked number below was generated by actually running
//! `pyswisseph` 2.10.03 (`swe.houses_armc`). They are NOT hand-derived.
//! Reproduce with:
//! ```text
//! python3 - <<'PY'
//! import swisseph as swe, math
//! def gmst_h(jd):
//!     t=(jd-2451545.0)/36525.0
//!     return ((280.46061837+360.98564736629*(jd-2451545.0)
//!              +0.000387933*t*t-t*t*t/38710000.0)/15.0)%24.0
//! def mean_obl_deg(jd):
//!     t=(jd-2451545.0)/36525.0
//!     return (84381.406-46.836769*t-0.0001831*t*t+0.00200340*t*t*t
//!             -0.000000576*t**4-0.0000000434*t**5)/3600.0
//! def armc_deg(jd,lon): return (((gmst_h(jd)+lon/15.0)%24.0)*15.0)%360.0
//! jd, lat, lon = 2451545.0, 28.0, 73.85
//! print(swe.houses_armc(armc_deg(jd,lon), lat, mean_obl_deg(jd), b'P'))
//! PY
//! ```
//!
//! # House systems Swiss `houses_armc` cannot supply a comparable 12-cusp array
//! for (and are therefore NOT baked here):
//! * `Gauquelin` (`G`) returns a 36-element sector array, not 12 cusps.
//! * `SunshineMakransky`/`SunshineTreindl` (`i`/`I`) need the Sun's declination
//!   (`ascmc9`); without it Swiss degenerates them to Placidus, so a comparison
//!   would not test XALEN's Sunshine path. Both are documented approximations.
//! * `AlcabitiusClassic` has no distinct Swiss `hsys` code (see
//!   `systems.rs::swiss_ephem_code` → `None`), so there is no Swiss oracle for it.
//!
//! `Zariel` is baked against Swiss `X` (Meridian): `systems.rs` documents Zariel
//! as XALEN's axial-rotation alias that reuses the Meridian computation.

use xalen_houses::{
    GeoLocation, HouseSystem, compute_houses, compute_ramc, gmst, local_sidereal_time,
};

/// IAU 2006 mean obliquity of the ecliptic, in **radians**, from a Julian Day.
///
/// Byte-for-byte the same polynomial as `xalen_coords::obliquity::mean_obliquity`
/// and the vertex-regression helper — this is the `epsilon` XALEN production
/// callers feed into `compute_houses`, and the same value used to generate the
/// Swiss reference cusps below.
fn mean_obliquity_rad(jd: f64) -> f64 {
    let t = (jd - 2_451_545.0) / 36525.0;
    let eps_arcsec = 84381.406 - 46.836769 * t - 0.0001831 * t * t + 0.00200340 * t * t * t
        - 0.000000576 * t.powi(4)
        - 0.0000000434 * t.powi(5);
    (eps_arcsec / 3600.0).to_radians()
}

/// XALEN's Right Ascension of the MC (RAMC) in radians, reproduced through the
/// crate's own public sidereal-time chain. The longitude here MUST match the
/// longitude used when the Swiss reference cusps were generated (73.85° E).
fn xalen_ramc(jd: f64, lon_deg: f64) -> f64 {
    compute_ramc(local_sidereal_time(gmst(jd), lon_deg))
}

/// Smallest unsigned separation between two angles in degrees, robust across the
/// 0°/360° wrap.
fn ang_sep_deg(a: f64, b: f64) -> f64 {
    let d = (a - b).rem_euclid(360.0);
    d.min(360.0 - d)
}

/// Reference longitude used for every row (matches the oracle generator).
const ORACLE_LON_DEG: f64 = 73.85;

/// Tight Swiss-match tolerance for algorithmically-exact systems.
const TIGHT_TOL_DEG: f64 = 0.01;

/// Loosened tolerance for systems XALEN documents as approximations
/// (not validated bit-for-bit against Swiss).
const APPROX_TOL_DEG: f64 = 5.0;

/// One oracle row: (system, jd_ut1, latitude_deg, 12 Swiss cusp longitudes deg).
type OracleRow = (HouseSystem, f64, f64, [f64; 12]);

/// Per-system Swiss-match tolerance. Loosened ONLY for systems XALEN itself
/// documents as approximations.
///
/// `PullenSinusoidalRatio` is explicitly documented in `cusps.rs` as an
/// "APPROXIMATION in the spirit of Pullen SR, not validated bit-for-bit against
/// the Swiss Ephemeris 'Q' algorithm", so it gets the loosened tolerance.
///
/// `APC`, `Sripati`, and `PullenSinusoidalDelta` are now EXACT re-implementations
/// of the Swiss `Y`/`S`/`L` algorithms (`apc_sector`, the trisected-Porphyry
/// midpoint, and the sinusoidal-delta quadrant split), so they are held to the
/// tight tolerance and pass it. (They previously used unvalidated approximations
/// and failed the tight tolerance by 49°/30°+/12° respectively.)
fn tolerance_for(system: HouseSystem) -> f64 {
    match system {
        HouseSystem::PullenSinusoidalRatio => APPROX_TOL_DEG,
        _ => TIGHT_TOL_DEG,
    }
}

